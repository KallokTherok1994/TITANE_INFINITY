#[tauri::command]
pub async fn create_module(
    intent: String,
    target_type: String,
) -> Result<GeneratedArtifact, String> {
    let engine = CreationEngine::new();

    let target = match target_type.as_str() {
        "rust" => TargetType::RustModule,
        "typescript" => TargetType::TypeScriptComponent,
        "react" => TargetType::ReactPage,
        _ => return Err("Unknown target type".to_string()),
    };

    let request = CreationRequest {
        id: uuid::Uuid::new_v4().to_string(),
        intent: intent.clone(),
        target_type: target,
        parameters: {
            let mut params = HashMap::new();
            params.insert("NAME".to_string(), "GeneratedModule".to_string());
            params.insert("FIELDS".to_string(), "data: String,".to_string());
            params
        },
    };

    engine.create_from_intent(request).await
}

