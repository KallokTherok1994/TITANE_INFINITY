// INITIALISATION
// ─────────────────────────────────────────────────────────────────────────────

pub fn init() -> AutomationEngineState {
    let mut configs = HashMap::new();

    // Enregistrer toutes les automations
    register_automations(&mut configs);

    let state = AutomationEngineState {
        configs: Arc::new(Mutex::new(configs)),
        history: Arc::new(Mutex::new(Vec::new())),
        cooldowns: Arc::new(Mutex::new(HashMap::new())),
        stats: Arc::new(Mutex::new(AutomationStats {
            total_executions: 0,
            successful_executions: 0,
            failed_executions: 0,
            total_xp_awarded: 0,
            executions_by_category: HashMap::new(),
            average_duration_ms: 0,
        })),
        running: Arc::new(Mutex::new(HashSet::new())),
    };

    // Phase 1 Stabilisation: Gérer lock poison
    let configs_len = match state.configs.lock() {
        Ok(c) => c.len(),
        Err(e) => {
            eprintln!("Warning: Automations configs lock poisoned in init, recovering: {}", e);
            e.into_inner().len()
        }
    };
    println!("[AUTOMATION] Engine initialized with {} automations", configs_len);

    state
}

