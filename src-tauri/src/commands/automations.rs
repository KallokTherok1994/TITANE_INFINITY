fn get_timestamp() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

fn generate_execution_id() -> String {
    format!("exec_{}_{}", get_timestamp(), rand::random::<u32>())
}

