/// Obtenir la liste de toutes les automations
#[tauri::command]
pub fn automation_list(
    state: State<AutomationEngineState>,
) -> Result<Vec<AutomationConfig>, TAPIError> {
    let configs = state.configs.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    Ok(configs.values().cloned().collect())
}

/// Obtenir les automations disponibles pour un mode et niveau de permission
#[tauri::command]
pub fn automation_get_available(
    mode_id: String,
    permission_level: u8,
    state: State<AutomationEngineState>,
) -> Result<Vec<AutomationConfig>, TAPIError> {
    let configs = state.configs.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    let available: Vec<AutomationConfig> = configs
        .values()
        .filter(|config| {
            // Vérifier permission
            if permission_level < config.required_permission {
                return false;
            }

            // Vérifier mode
            if let Some(ref allowed_modes) = config.allowed_modes {
                if !allowed_modes.contains(&mode_id) {
                    return false;
                }
            }

            true
        })
        .cloned()
        .collect();

    Ok(available)
}

/// Valider une requête d'automation (sans exécuter)
#[tauri::command]
pub fn automation_validate(
    request: AutomationRequest,
    state: State<AutomationEngineState>,
) -> Result<bool, TAPIError> {
    let configs = state.configs.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    let config = configs.get(&request.automation_id).ok_or_else(|| {
        TAPIError::not_found(format!("Automation '{}' inconnue", request.automation_id))
    })?;

    let cooldowns = state.cooldowns.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    let running = state.running.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    match validate_automation_request(config, &request, &cooldowns, &running) {
        Ok(()) => Ok(true),
        Err(msg) => Err(TAPIError::validation(msg)),
    }
}

/// Exécuter une automation
#[tauri::command]
pub fn automation_execute(
    request: AutomationRequest,
    state: State<AutomationEngineState>,
) -> Result<AutomationResult, TAPIError> {
    let execution_id = generate_execution_id();
    let started_at = get_timestamp();

    // Récupérer la config
    let config = {
        let configs = state.configs.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;

        configs.get(&request.automation_id).ok_or_else(|| {
            TAPIError::not_found(format!("Automation '{}' inconnue", request.automation_id))
        })?.clone()
    };

    // Valider la requête
    {
        let cooldowns = state.cooldowns.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;

        let running = state.running.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;

        validate_automation_request(&config, &request, &cooldowns, &running)
            .map_err(|msg| TAPIError::validation(msg))?;
    }

    // Marquer comme en cours
    {
        let mut running = state.running.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;
        running.insert(request.automation_id.clone());
    }

    // Simuler l'exécution (dans une vraie implémentation, on exécuterait l'automation)
    let mut logs = Vec::new();
    logs.push(AutomationLog {
        timestamp: started_at,
        level: "info".to_string(),
        message: format!("Démarrage de '{}'", config.name),
    });

    // Simulation réussie
    let completed_at = get_timestamp();
    let duration_ms = completed_at - started_at;

    logs.push(AutomationLog {
        timestamp: completed_at,
        level: "info".to_string(),
        message: format!("'{}' terminée avec succès", config.name),
    });

    let xp_awarded = config.base_xp_reward;

    // Créer le résultat
    let result = AutomationResult {
        execution_id,
        automation_id: request.automation_id.clone(),
        status: ExecutionStatus::Success,
        started_at,
        completed_at: Some(completed_at),
        duration_ms: Some(duration_ms),
        output: Some(serde_json::json!({
            "message": format!("Automation '{}' exécutée avec succès", config.name)
        })),
        error: None,
        logs,
        xp_awarded,
    };

    // Retirer de "running"
    {
        let mut running = state.running.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;
        running.remove(&request.automation_id);
    }

    // Mettre à jour cooldown
    {
        let mut cooldowns = state.cooldowns.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;
        cooldowns.insert(request.automation_id.clone(), completed_at + config.cooldown_ms);
    }

    // Ajouter à l'historique
    {
        let mut history = state.history.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;
        history.push(result.clone());

        // Limiter à 100 entrées
        if history.len() > 100 {
            history.drain(0..(history.len() - 100));
        }
    }

    // Mettre à jour les stats
    {
        let mut stats = state.stats.lock().map_err(|e| {
            TAPIError::internal(format!("Lock error: {}", e))
        })?;

        stats.total_executions += 1;
        stats.successful_executions += 1;
        stats.total_xp_awarded += xp_awarded as u64;

        let category_key = format!("{:?}", config.category);
        *stats.executions_by_category.entry(category_key).or_insert(0) += 1;

        // Recalculer moyenne
        if stats.total_executions > 0 {
            stats.average_duration_ms = ((stats.average_duration_ms * (stats.total_executions - 1)) + duration_ms) / stats.total_executions;
        }
    }

    println!("[AUTOMATION] Exécuté: {} | XP: +{} | Durée: {}ms", config.name, xp_awarded, duration_ms);

    Ok(result)
}

/// Obtenir l'historique des exécutions
#[tauri::command]
pub fn automation_get_history(
    limit: Option<usize>,
    state: State<AutomationEngineState>,
) -> Result<Vec<AutomationResult>, TAPIError> {
    let history = state.history.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    let limit = limit.unwrap_or(20).min(100);
    let start = if history.len() > limit {
        history.len() - limit
    } else {
        0
    };

    Ok(history[start..].to_vec())
}

/// Obtenir les statistiques d'automations
#[tauri::command]
pub fn automation_get_stats(
    state: State<AutomationEngineState>,
) -> Result<AutomationStats, TAPIError> {
    let stats = state.stats.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    Ok(stats.clone())
}

/// Vérifier les cooldowns actifs
#[tauri::command]
pub fn automation_get_cooldowns(
    state: State<AutomationEngineState>,
) -> Result<HashMap<String, u64>, TAPIError> {
    let cooldowns = state.cooldowns.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    let now = get_timestamp();

    // Retourner seulement les cooldowns actifs (timestamp > now)
    let active: HashMap<String, u64> = cooldowns
        .iter()
        .filter(|(_, &end_time)| end_time > now)
        .map(|(id, &end_time)| (id.clone(), end_time - now))
        .collect();

    Ok(active)
}

/// Annuler une automation en cours (si cancellable)
#[tauri::command]
pub fn automation_cancel(
    automation_id: String,
    state: State<AutomationEngineState>,
) -> Result<bool, TAPIError> {
    let mut running = state.running.lock().map_err(|e| {
        TAPIError::internal(format!("Lock error: {}", e))
    })?;

    if running.remove(&automation_id) {
        println!("[AUTOMATION] Annulée: {}", automation_id);
        Ok(true)
    } else {
        Ok(false)
    }
}

