/// État du système d'automations
pub struct AutomationEngineState {
    /// Configurations des automations
    configs: Arc<Mutex<HashMap<String, AutomationConfig>>>,
    /// Historique des exécutions (limité à 100)
    history: Arc<Mutex<Vec<AutomationResult>>>,
    /// Cooldowns actifs (automation_id -> timestamp fin)
    cooldowns: Arc<Mutex<HashMap<String, u64>>>,
    /// Statistiques
    stats: Arc<Mutex<AutomationStats>>,
    /// Exécutions en cours
    running: Arc<Mutex<HashSet<String>>>,
}

