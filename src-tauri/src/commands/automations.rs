/// Valider qu'une automation peut être exécutée
fn validate_automation_request(
    config: &AutomationConfig,
    request: &AutomationRequest,
    cooldowns: &HashMap<String, u64>,
    running: &HashSet<String>,
) -> Result<(), String> {
    let now = get_timestamp();

    // Vérifier si déjà en cours
    if running.contains(&request.automation_id) {
        return Err(format!("Automation '{}' déjà en cours d'exécution", config.name));
    }

    // Vérifier cooldown
    if let Some(cooldown_end) = cooldowns.get(&request.automation_id) {
        if *cooldown_end > now {
            let remaining = (*cooldown_end - now) / 1000;
            return Err(format!(
                "Automation '{}' en cooldown ({} secondes restantes)",
                config.name, remaining
            ));
        }
    }

    // Vérifier permission
    if request.permission_level < config.required_permission {
        return Err(format!(
            "Permission insuffisante pour '{}' (niveau {} requis, {} fourni)",
            config.name, config.required_permission, request.permission_level
        ));
    }

    // Vérifier mode autorisé
    if let Some(ref allowed_modes) = config.allowed_modes {
        if !allowed_modes.contains(&request.mode_id) {
            return Err(format!(
                "Mode '{}' non autorisé pour automation '{}'",
                request.mode_id, config.name
            ));
        }
    }

    // Vérifier confirmation si nécessaire
    if config.requires_confirmation && !request.user_confirmed {
        return Err(format!(
            "Automation '{}' nécessite une confirmation utilisateur",
            config.name
        ));
    }

    Ok(())
}

