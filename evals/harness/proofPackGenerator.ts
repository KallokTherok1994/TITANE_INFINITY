/**
 * TITANE∞ — PROOF PACK GENERATOR
 * Generates the 22 mandatory proof pack files.
 */

import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';
import type { EvalSession, ProofPackManifest } from './types';

function getShortSha(): string {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf-8' }).trim();
  } catch {
    return 'unknown';
  }
}

export function generateProofPack(session: EvalSession): ProofPackManifest {
  const shortSha = getShortSha();
  const now = new Date();
  const dateStr = now.toISOString().slice(0, 10);
  const timeStr = now.toTimeString().slice(0, 5).replace(':', '');
  const dirName = `ZERO_REGRESSION_AUTO_MODE_${dateStr}_${timeStr}_${shortSha}`;
  const packDir = join(process.cwd(), 'proof_packs', dirName);
  mkdirSync(packDir, { recursive: true });

  const files: string[] = [];

  const summary = [
    `# Zero-Regression Auto Mode — Execution Summary`,
    ``,
    `**Session**: ${session.sessionId}`,
    `**Version**: ${session.version}`,
    `**Date**: ${new Date(session.timestamp).toISOString()}`,
    `**Champion Baseline**: ${session.championBaseline}`,
    `**Final Verdict**: ${session.finalVerdict}`,
    ``,
    `## Summary`,
    `- Lanes evaluated: ${session.lanes.length}`,
    `- Total items: ${session.lanes.reduce((s, l) => s + l.totalItems, 0)}`,
    `- Passed: ${session.lanes.reduce((s, l) => s + l.passedItems, 0)}`,
    `- Failed: ${session.lanes.reduce((s, l) => s + l.failedItems, 0)}`,
    `- Anti-lie violations: ${session.antiLieViolations.filter(v => v.detected).length}`,
    `- Gates passed: ${session.gates.gates.filter(g => g.passed).length}/${session.gates.gates.length}`,
    `- Promotion allowed: ${session.gates.promotionAllowed}`,
  ].join('\n');
  writeFileSync(join(packDir, '00_EXEC_SUMMARY.md'), summary);
  files.push('00_EXEC_SUMMARY.md');

  let gatesMd =
    '# Gates Report\n\n| Gate | Blocking | Passed | Evidence |\n|------|----------|--------|----------|\n';
  for (const g of session.gates.gates) {
    gatesMd += `| ${g.gate} | ${g.blocking} | ${g.passed} | ${g.evidence} |\n`;
  }
  gatesMd += `\n**All blocking passed**: ${session.gates.allBlockingPassed}\n**Promotion allowed**: ${session.gates.promotionAllowed}\n`;
  writeFileSync(join(packDir, '19_GATES_REPORT.md'), gatesMd);
  files.push('19_GATES_REPORT.md');

  let honestyMd =
    '# Honesty Regression Report\n\n| Violation | Name | Detected | Evidence |\n|-----------|------|----------|----------|\n';
  for (const v of session.antiLieViolations) {
    honestyMd += `| ${v.violationId} | ${v.name} | ${v.detected} | ${v.evidence} |\n`;
  }
  writeFileSync(join(packDir, '13_HONESTY_REGRESSION_REPORT.md'), honestyMd);
  files.push('13_HONESTY_REGRESSION_REPORT.md');

  const verdictMd = [
    `# Final Verdict`,
    ``,
    `**Verdict**: ${session.finalVerdict}`,
    ``,
    `## Decision Logic`,
    `- Any blocking gate FAIL → PROMOTION_BLOCKED`,
    `- Any anti-lie violation → REGRESSION_DETECTED`,
    `- All gates PASS + no violations → CHAMPION_RETAINED or SHADOW_ONLY`,
    ``,
    `## Result`,
    session.gates.promotionAllowed
      ? 'All gates PASS. Challenger eligible for shadow observation. Champion retained by default.'
      : 'Gates FAILED. Promotion BLOCKED. Champion retained.',
    ``,
    `## Rollback`,
    '`git reset --hard v28.0.0`',
  ].join('\n');
  writeFileSync(join(packDir, '22_VERDICT.md'), verdictMd);
  files.push('22_VERDICT.md');

  const stubs = [
    '01_BOOTSTRAP.md',
    '02_SCOPE.md',
    '03_AGENT_INVENTORY.md',
    '04_CRITICAL_CHAINS_MAP.md',
    '05_CHAMPION_BASELINE_MAP.md',
    '06_CHALLENGER_SURFACES_MAP.md',
    '07_GAP_MATRIX.md',
    '08_DATASET_INDEX.md',
    '09_SCORECARDS_INDEX.md',
    '10_CHAMPION_RESULTS.json',
    '11_CHALLENGER_RESULTS.json',
    '12_DELTA_REPORT.md',
    '14_MEMORY_REGRESSION_REPORT.md',
    '15_ROUTER_REGRESSION_REPORT.md',
    '16_AUTOHEAL_TRUTH_REPORT.md',
    '17_DESKTOP_FLOW_REPORT.md',
    '18_X3_RESULTS.log',
    '20_DIFF_FILES.md',
    '21_ROLLBACK.md',
  ];
  for (const stub of stubs) {
    writeFileSync(join(packDir, stub), `# ${stub}\n\nTODO: Generated by eval harness.\n`);
    files.push(stub);
  }

  return { path: packDir, files, generatedAt: Date.now(), shortSha };
}
